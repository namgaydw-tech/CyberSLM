"""A new Streamlit page: real model-to-model handoff, without overwriting the app."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import streamlit as st

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from cyberslm.two_model_bridge import run_bridge  # noqa: E402

st.set_page_config(page_title="CyberSLM → Qwen Bridge", page_icon="🔗", layout="wide")
st.title("🔗 CyberSLM-35M → Verification → Qwen")
st.caption(
    "Actual two-model orchestration · scratch model predictions and verified facts shown separately"
)
st.info(
    "This page combines two *different* inference models. CyberSLM-35M is "
    "scratch-trained; Qwen2.5-1.5B is externally pretrained."
)

provider = st.sidebar.selectbox(
    "Qwen inference runtime",
    ["Automatic: Ollama → LM Studio", "Ollama preferred", "LM Studio preferred"],
)
use_rag = st.sidebar.toggle("Use trusted cybersecurity RAG", value=False)


@st.cache_resource
def get_retriever():
    from cyberslm.rag import KnowledgeRetriever

    return KnowledgeRetriever(ROOT / "data" / "rag" / "cyberslm_trusted_knowledge_v1")


example = [
    {
        "event_type": "EVENT_READ",
        "source_entity": "fictional-host-a",
        "destination_entity": "fictional-file-1",
        "timestamp": 1.0,
    },
    {
        "event_type": "EVENT_WRITE",
        "source_entity": "fictional-host-a",
        "destination_entity": "fictional-file-2",
        "timestamp": 2.0,
    },
    {
        "event_type": "EVENT_READ",
        "source_entity": "fictional-host-b",
        "destination_entity": "fictional-file-1",
        "timestamp": 3.0,
    },
]

st.write("**1. Provide fictional structured event evidence**")
raw = st.text_area("Event JSON", value=json.dumps(example, indent=2), height=245)
question = st.text_input("2. Ask an evidence question", "count unique event types")

if st.button("Run both models and show the handoff", type="primary"):
    try:
        events = json.loads(raw)
        with st.spinner("CyberSLM inference → verification → Qwen explanation"):
            report = run_bridge(
                events,
                question,
                provider={
                    "Automatic: Ollama → LM Studio": "auto",
                    "Ollama preferred": "ollama",
                    "LM Studio preferred": "lm_studio",
                }[provider],
                retriever=get_retriever() if use_rag else None,
            )
        st.subheader("3. Model communication receipt")
        left, mid, right = st.columns(3)
        with left:
            st.write("**Scratch CyberSLM-35M**")
            st.code(report.scratch_prediction)
            st.caption(
                f"Neural prediction · {report.scratch_latency_seconds:.2f}s · "
                f"runtime: {report.scratch_runtime}"
            )
        with mid:
            st.write("**Independent verification**")
            st.code(
                report.verified_answer if report.verified_answer is not None else "NOT VERIFIED"
            )
            st.caption(report.verification)
        with right:
            st.write("**Agreement**")
            if report.agrees is True:
                st.success("Prediction agrees")
            elif report.agrees is False:
                st.error("Disagreement: reference takes precedence")
            else:
                st.warning("Comparison not applicable")

        st.subheader("4. Qwen explanation — receives both outputs")
        st.write(report.explanation)
        st.caption(
            f"Generated by {report.explanation_model} through "
            f"{report.explanation_provider} · {report.explanation_latency_seconds:.2f}s"
        )
        if report.explanation_attempts:
            st.caption("Explanation runtime path: " + " → ".join(report.explanation_attempts))
        if report.sources:
            with st.expander("Retrieved reference documents"):
                for item in report.sources:
                    st.markdown(f"- [{item['title']}]({item['url']})")
        with st.expander("Show the exact handoff data sent to Qwen"):
            st.json(
                {
                    "facts": report.facts,
                    "scratch_model": report.scratch_model,
                    "scratch_prediction_unverified": report.scratch_prediction,
                    "verification": report.verification,
                    "verified_answer_if_supported": report.verified_answer,
                    "agreement": report.agrees,
                    "qwen_model": report.explanation_model,
                }
            )
    except (ValueError, KeyError, TypeError, OSError, RuntimeError) as error:
        st.error(f"Bridge did not complete: {error}")
